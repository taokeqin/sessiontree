//! Markdown and CSV reports for the current scope.
//!
//! Reports are plain data for a team lead to forward: the UI's translated
//! range and metric names are passed in, while table headings stay English.

use crate::model::*;
use std::fmt::Write;

const TOP: usize = 20;

/// A Markdown report of `node` for the current period and metric.
pub(crate) fn markdown(
    node: &Node,
    range_title: &str,
    metric: Metric,
    metric_label: &str,
    pricing_source: &str,
) -> String {
    let mut out = String::new();
    writeln!(out, "# SessionTree report\n").unwrap();
    writeln!(out, "- **Scope:** {}", cell(&scope_name(node))).unwrap();
    writeln!(out, "- **Period:** {}", cell(range_title)).unwrap();
    writeln!(out, "- **Metric:** {}\n", cell(metric_label)).unwrap();

    writeln!(out, "## Summary\n").unwrap();
    writeln!(out, "| Metric | Value |").unwrap();
    writeln!(out, "| --- | ---: |").unwrap();
    writeln!(out, "| Sessions | {} |", count(node.sessions)).unwrap();
    writeln!(out, "| Messages | {} |", count(node.messages)).unwrap();
    writeln!(out, "| Input tokens | {} |", compact(node.input)).unwrap();
    writeln!(out, "| Output tokens | {} |", compact(node.output)).unwrap();
    writeln!(out, "| Cache tokens | {} |", compact(node.cache())).unwrap();
    writeln!(out, "| Cost (est.) | {} |\n", cost_text(node)).unwrap();

    if !node.children.is_empty() {
        writeln!(out, "## Breakdown\n").unwrap();
        writeln!(
            out,
            "| {} | Sessions | Messages | Tokens | Cost (est.) |",
            match node.kind.as_str() {
                "root" => "Agent",
                "agent" => "Project",
                _ => "Session",
            }
        )
        .unwrap();
        writeln!(out, "| --- | ---: | ---: | ---: | ---: |").unwrap();
        let mut children = node.children.clone();
        children.sort_by(|a, b| {
            metric
                .weight(b)
                .partial_cmp(&metric.weight(a))
                .unwrap_or(std::cmp::Ordering::Equal)
        });
        for child in children.iter().take(TOP) {
            writeln!(
                out,
                "| {} | {} | {} | {} | {} |",
                cell(&scope_name(child)),
                count(child.sessions),
                count(child.messages),
                compact(child.tokens()),
                cost_text(child)
            )
            .unwrap();
        }
        out.push('\n');
    }

    let mut sessions = Vec::new();
    collect_sessions(node, &mut sessions);
    sessions.sort_by(|a, b| {
        metric
            .weight(b.2)
            .partial_cmp(&metric.weight(a.2))
            .unwrap_or(std::cmp::Ordering::Equal)
    });
    if !sessions.is_empty() {
        writeln!(out, "## Top sessions\n").unwrap();
        writeln!(
            out,
            "| Session | Agent | Project | Model | Messages | Tokens | Cost (est.) |"
        )
        .unwrap();
        writeln!(out, "| --- | --- | --- | --- | ---: | ---: | ---: |").unwrap();
        for (agent, project, session) in sessions.iter().take(TOP) {
            writeln!(
                out,
                "| {} | {} | {} | {} | {} | {} | {} |",
                cell(&scope_name(session)),
                cell(agent),
                cell(project),
                cell(&session.model),
                count(session.messages),
                compact(session.tokens()),
                cost_text(session)
            )
            .unwrap();
        }
        out.push('\n');
    }

    writeln!(out, "---\n").unwrap();
    writeln!(
        out,
        "Costs are estimates from {}. Token counts come from local logs.",
        cell(pricing_source)
    )
    .unwrap();
    writeln!(out, "Generated by SessionTree; nothing was uploaded.").unwrap();
    out
}

/// One CSV row per session under `node`, with the agent and project it is in.
pub(crate) fn csv(node: &Node) -> String {
    let mut out = String::from(
        "agent,project,session,model,messages,input,output,cache_read,cache_write,cost_estimated,first,last,file\n",
    );
    write_rows(node, "", "", &mut out);
    out
}

fn write_rows(node: &Node, agent: &str, project: &str, out: &mut String) {
    match node.kind.as_str() {
        "root" => {
            for child in &node.children {
                write_rows(child, agent, project, out);
            }
        }
        "agent" => {
            for child in &node.children {
                write_rows(child, &node.name, project, out);
            }
        }
        "project" => {
            let agent = if agent.is_empty() {
                node.tool.as_str()
            } else {
                agent
            };
            for child in &node.children {
                write_rows(child, agent, &node.name, out);
            }
        }
        "session" => {
            let cost = if node.tool == "Cursor" && node.cost <= 0.0 {
                String::new()
            } else {
                format!("{:.6}", node.cost)
            };
            writeln!(
                out,
                "{},{},{},{},{},{},{},{},{},{},{},{},{}",
                field(agent),
                field(project),
                field(&scope_name(node)),
                field(&node.model),
                node.messages,
                node.input,
                node.output,
                node.cache_read,
                node.cache_write,
                cost,
                field(&stamp(node.first_ts)),
                field(&stamp(node.last_ts)),
                field(&node.file)
            )
            .unwrap();
        }
        _ => {}
    }
}

fn collect_sessions<'a>(node: &'a Node, out: &mut Vec<(&'a str, &'a str, &'a Node)>) {
    match node.kind.as_str() {
        "root" => {
            for agent in &node.children {
                collect_sessions(agent, out);
            }
        }
        "agent" => {
            for project in &node.children {
                collect_sessions(project, out);
            }
        }
        "project" => {
            for session in &node.children {
                out.push((node.tool.as_str(), node.name.as_str(), session));
            }
        }
        "session" => out.push((node.tool.as_str(), "", node)),
        _ => {}
    }
}

fn scope_name(node: &Node) -> String {
    match node.kind.as_str() {
        "root" => "All sessions".into(),
        "project" if !node.title.is_empty() => node.title.clone(),
        _ => node.name.clone(),
    }
}

fn cell(value: &str) -> String {
    value.replace('|', "\\|").replace('\n', " ")
}

fn field(value: &str) -> String {
    format!("\"{}\"", value.replace('"', "\"\""))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::Arc;

    fn tree() -> Node {
        let session = Arc::new(Node {
            path: "agent:Claude Code|project:/work/x|session:s1".into(),
            name: "Fix, the \"login\"".into(),
            kind: "session".into(),
            tool: "Claude Code".into(),
            model: "claude-sonnet-4".into(),
            messages: 3,
            input: 1200,
            output: 3400,
            cost: 0.25,
            ..Node::default()
        });
        let project = Arc::new(Node {
            path: "agent:Claude Code|project:/work/x".into(),
            name: "x".into(),
            title: "/work/x".into(),
            kind: "project".into(),
            tool: "Claude Code".into(),
            sessions: 1,
            messages: 3,
            input: 1200,
            output: 3400,
            cost: 0.25,
            children: vec![session],
            ..Node::default()
        });
        let agent = Arc::new(Node {
            path: "agent:Claude Code".into(),
            name: "Claude Code".into(),
            kind: "agent".into(),
            tool: "Claude Code".into(),
            sessions: 1,
            messages: 3,
            input: 1200,
            output: 3400,
            cost: 0.25,
            children: vec![project],
            ..Node::default()
        });
        Node {
            path: "root".into(),
            name: "All sessions".into(),
            kind: "root".into(),
            sessions: 1,
            messages: 3,
            input: 1200,
            output: 3400,
            cost: 0.25,
            children: vec![agent],
            ..Node::default()
        }
    }

    #[test]
    fn markdown_summarizes_the_scope() {
        let report = markdown(
            &tree(),
            "Last 7 days",
            Metric::Tokens,
            "Tokens",
            "test table",
        );
        assert!(report.contains("# SessionTree report"));
        assert!(report.contains("**Period:** Last 7 days"));
        assert!(report.contains("| Sessions | 1 |"));
        assert!(report.contains("Claude Code"));
        assert!(report.contains("Costs are estimates from test table."));
    }

    #[test]
    fn csv_quotes_commas_and_quotes() {
        let csv = csv(&tree());
        assert!(csv.starts_with("agent,project,session,model,"));
        assert!(csv.contains("\"Fix, the \"\"login\"\"\""));
        assert!(csv.contains("\"Claude Code\",\"x\""));
    }
}
